"""SQLite translation of the team's immutable 11-table MySQL logical schema.

Only SQLite-specific syntax/type representations differ: INT AUTO_INCREMENT
becomes INTEGER PRIMARY KEY AUTOINCREMENT, MySQL BOOLEAN is SQLite INTEGER,
LONGTEXT/TEXT and VARCHAR are SQLite text affinity, DATETIME remains DATETIME.
All original table/column names, nullability, defaults and foreign keys remain.
"""

SCHEMA = """
CREATE TABLE IF NOT EXISTS Customer (
 CustomerID INTEGER PRIMARY KEY AUTOINCREMENT,
 OrganizationName VARCHAR(100) NOT NULL,
 Status VARCHAR(20) DEFAULT 'ACTIVE',
 CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS Users (
 UserID INTEGER PRIMARY KEY AUTOINCREMENT,
 UserName VARCHAR(50) NOT NULL UNIQUE,
 Email VARCHAR(100) NOT NULL UNIQUE,
 PasswordHash CHAR(60) NOT NULL,
 FirstName VARCHAR(50), LastName VARCHAR(50),
 IsActive BOOLEAN DEFAULT TRUE,
 CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP,
 CustomerID INT,
 CONSTRAINT fk_users_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS Role (
 RoleID INTEGER PRIMARY KEY AUTOINCREMENT,
 RoleName VARCHAR(50) NOT NULL UNIQUE,
 Description TEXT
);
CREATE TABLE IF NOT EXISTS UserRole (
 UserID INT NOT NULL, RoleID INT NOT NULL,
 AssignedAt DATETIME DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (UserID, RoleID),
 CONSTRAINT fk_userrole_user FOREIGN KEY (UserID) REFERENCES Users(UserID) ON DELETE CASCADE,
 CONSTRAINT fk_userrole_role FOREIGN KEY (RoleID) REFERENCES Role(RoleID) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS API_Key (
 KeyID INTEGER PRIMARY KEY AUTOINCREMENT,
 BearerTokenHash VARCHAR(255) NOT NULL UNIQUE,
 KeyName VARCHAR(50) DEFAULT 'Primary Key',
 IsActive BOOLEAN DEFAULT TRUE,
 MonthlyQuota INT DEFAULT 1000,
 RateLimitPerMin INT DEFAULT 120,
 ExpiresAt DATETIME,
 CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP,
 CustomerID INT NOT NULL,
 CONSTRAINT fk_api_key_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS CaptchaType (
 TypeCode VARCHAR(50) PRIMARY KEY,
 TypeName VARCHAR(100) NOT NULL,
 InputFormat VARCHAR(30) NOT NULL DEFAULT 'IMAGE_BASE64',
 IsSupported BOOLEAN DEFAULT TRUE,
 Description TEXT
);
CREATE TABLE IF NOT EXISTS AI_Model (
 Model_ID INTEGER PRIMARY KEY AUTOINCREMENT,
 ModelName VARCHAR(100) NOT NULL,
 Version VARCHAR(20) NOT NULL,
 Framework VARCHAR(50) DEFAULT 'PyTorch',
 ArtifactLocation VARCHAR(255) NOT NULL,
 IsActive BOOLEAN DEFAULT TRUE,
 CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS SolverAdapter (
 SolverID INTEGER PRIMARY KEY AUTOINCREMENT,
 AdapterName VARCHAR(100) NOT NULL,
 ProvidesConfidence BOOLEAN DEFAULT TRUE,
 IsActive BOOLEAN DEFAULT TRUE,
 TypeCode VARCHAR(50) NOT NULL,
 Model_ID INT NOT NULL,
 CONSTRAINT fk_solveradapter_type FOREIGN KEY (TypeCode) REFERENCES CaptchaType(TypeCode) ON DELETE CASCADE,
 CONSTRAINT fk_solveradapter_model FOREIGN KEY (Model_ID) REFERENCES AI_Model(Model_ID) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS SolvingRequest (
 RequestID INTEGER PRIMARY KEY AUTOINCREMENT,
 CaptchaContentPayload LONGTEXT NOT NULL,
 PredictedSolution VARCHAR(255),
 Confidence DECIMAL(5,4),
 ProcessingTimeMs INT,
 Status VARCHAR(30) NOT NULL,
 ErrorMessage TEXT,
 RequestedAt DATETIME DEFAULT CURRENT_TIMESTAMP,
 CustomerID INT NOT NULL,
 KeyID INT NOT NULL,
 DeclaredTypeCode VARCHAR(50) NOT NULL,
 SolverID INT,
 CONSTRAINT fk_solvingrequest_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID) ON DELETE CASCADE,
 CONSTRAINT fk_solvingrequest_key FOREIGN KEY (KeyID) REFERENCES API_Key(KeyID) ON DELETE CASCADE,
 CONSTRAINT fk_solvingrequest_type FOREIGN KEY (DeclaredTypeCode) REFERENCES CaptchaType(TypeCode) ON DELETE CASCADE,
 CONSTRAINT fk_solvingrequest_solver FOREIGN KEY (SolverID) REFERENCES SolverAdapter(SolverID) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS UsageBatch (
 BatchID INTEGER PRIMARY KEY AUTOINCREMENT,
 ChallengeCount INT DEFAULT 100,
 Status VARCHAR(30) DEFAULT 'COMPLETED',
 BatchStartedAt DATETIME NOT NULL,
 BatchCompletedAt DATETIME NOT NULL,
 TotalProcessingTimeMs BIGINT NOT NULL,
 CustomerID INT NOT NULL,
 CONSTRAINT fk_usagebatch_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS SystemAuditLog (
 LogID INTEGER PRIMARY KEY AUTOINCREMENT,
 EventType VARCHAR(50) NOT NULL,
 Severity VARCHAR(20) DEFAULT 'INFO',
 Details TEXT NOT NULL,
 IPAddress VARCHAR(45),
 Timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
 CustomerID INT,
 UserID INT,
 CONSTRAINT fk_auditlog_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID) ON DELETE SET NULL,
 CONSTRAINT fk_auditlog_user FOREIGN KEY (UserID) REFERENCES Users(UserID) ON DELETE SET NULL
);
"""
